test('tools hub opens a configurable metronome', async ({ page }, testInfo) => {
  await page.goto('/tools')
  await expect(page.getByRole('heading', { name: 'Tools' })).toBeVisible()
  await page.getByRole('link', { name: /Open metronome/ }).click()
  await expect(page.getByRole('heading', { name: 'Metronome' })).toBeVisible()
  await page.getByLabel('BPM').fill('120')
  await page.getByLabel('Beats per bar', { exact: true }).selectOption('3')
  const snare = page.locator('.sound-picker label').filter({ hasText: 'Snare' })
  await snare.click()
  await expect(snare.locator('input')).toBeChecked()
  await expect(page.locator('.beat-dots i')).toHaveCount(3)
  await expect(page.getByText('120', { exact: true })).toBeVisible()
  if (testInfo.project.name === 'desktop') {
    await page.getByRole('button', { name: 'Start' }).click()
    await expect(page.getByRole('button', { name: 'Stop' })).toBeVisible()
  } else {
    await page.getByRole('button', { name: 'Start' }).click()
    await expect(page.getByRole('alert')).toContainText('Web Audio')
  }
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  expect(overflow).toBe(false)
})

test('tab editor accepts frets, note names, timing, and saves its draft', async ({ page }) => {
  await page.goto('/tab-editor')
  await expect(page.getByRole('heading', { name: 'Tab editor' })).toBeVisible()
  const highE = page.getByRole('spinbutton', { name: 'Beat 1, High E string fret' })
  await highE.fill('3')
  await page.getByRole('button', { name: 'ABC notes' }).click()
  await expect(page.locator('.tab-cell.selected small')).toHaveText('G4')
  await page.getByLabel('Duration').selectOption('0.5')
  await page.getByRole('button', { name: 'Add beat' }).click()
  await expect(page.locator('.tab-step-head')).toHaveCount(9)
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: 'Beat 1, High E string fret' })).toHaveValue('3')
  await expect(page.getByRole('link', { name: 'Tab Editor' })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  expect(overflow).toBe(false)
})
